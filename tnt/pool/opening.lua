--- Учёт отказов открытия: пауза после отказа и приговор ему.
---
--- Отказ `open` — сведения о службе, а не одна неудача, и пул помнит их
--- между попытками: сколько отказов подряд, до какого мига не открывать,
--- чем кончилась последняя попытка и есть ли смысл её повторять. Меняются
--- они вместе и читаются вместе, поэтому живут одной записью, а не
--- россыпью полей пула, у которого и без того выдача, возврат и уборка.
---
--- Пауза удваивается с каждым отказом подряд: первый отказ мог быть
--- случайностью, десятый означает, что службы нет, и сотня попыток
--- в секунду мешает ей подняться ровно тогда, когда она поднимается.
---
--- Окончательный отказ — тот, про который сама `open` сказала, что
--- повторять бессмысленно: неверный пароль, нет базы, нет прав. Время его
--- не лечит, и держать взявшего до конца срока ради попыток, которые
--- кончатся тем же, незачем. Слово берётся только явное — поле `retriable`,
--- равное `false`, у отказа, который умеет его отдать: у таблицы и у
--- `box.error` с полезной нагрузкой. Отказ без такого слова остаётся
--- временным: служба, моргнувшая на полсекунды, иначе уронила бы все
--- запросы разом.
---
--- Пауза после окончательного отказа остаётся: неверный пароль, который
--- пробуют сотней файберов в секунду, — это сотня записей в журнале
--- безопасности службы, а у иных служб и запертая учётная запись. После
--- паузы вход пробуют снова: пароль могли и поправить.

local settings_of = require('tnt.pool.settings')

---@class TntPoolOpening
---@field cooldown number С какой паузы начинается остановка; 0 — без паузы
---@field streak integer Сколько отказов подряд
---@field blocked_until number|nil До какого мига не открывать; пусто — можно
---@field last_error string|nil Чем кончилась последняя неудачная попытка
---@field final any Окончательный отказ последней попытки, как его дала `open`; пусто — повторять стоит
local Module = {}
Module.__index = Module

--- Заводит учёт, в котором отказов ещё не было.
---@param cooldown number С какой паузы начинать остановку после отказа
---@return TntPoolOpening
function Module.new(cooldown)
    return setmetatable({ cooldown = cooldown, streak = 0 }, Module)
end

--- Отказ, если `open` назвала его окончательным.
---
--- Поле читается под pcall: у пустого и у числового отказа полей нет
--- вовсе, а чужая метатаблица вправе бросить — и беда службы стала бы
--- падением взявшего.
---@param err any Что сказала `open`
---@return any final Тот же отказ либо nil
local function final_of(err)
    local read, retriable = pcall(function()
        return err.retriable
    end)

    if not read or retriable ~= false then
        return nil
    end

    return err
end

--- Запоминает отказ и назначает паузу.
---@param err any Что сказала `open`
---@param now number Когда отказ случился: после похода `open` в сеть, а не до него
function Module:failed(err, now)
    self.streak = self.streak + 1
    self.final = final_of(err)
    self.last_error = ('открыть соединение не удалось: %s'):format(
        tostring(err or 'причина не названа')
    )

    local delay = self.cooldown * 2 ^ (self.streak - 1)

    self.blocked_until = now + math.min(delay, settings_of.MAX_OPEN_COOLDOWN)
end

--- Открытие удалось: отказы и приговор считаются заново.
---
--- Пауза остаётся: её назначил отказ соседнего открытия, которое шло
--- одновременно с удачным, и служба, отказавшая ему, могла отказать
--- и следующему. Текст последнего отказа остаётся тоже — это след
--- для `stats`, а не состояние службы.
function Module:succeeded()
    self.streak = 0
    self.final = nil
end

--- Нет ли паузы в этот миг.
---
--- Пауза хранится мигом, до которого открывать нельзя, и пустотой, когда
--- паузы нет. Пустотой, а не нулём: ноль — законное показание часов,
--- и «пауза до нуля» не отличалась бы от «паузы нет». Держалось бы это
--- на том, что часы не показывают меньше нуля, а монотонные о своей точке
--- отсчёта не обещают ничего, подменённые же в проверках показывают что
--- угодно.
---@param now number
---@return boolean
function Module:allows(now)
    local blocked = self.blocked_until

    return blocked == nil or now >= blocked
end

--- Сколько спать до следующей попытки.
---
--- Не до конца срока: если открыть новое соединение мешает только пауза,
--- ждущий обязан проснуться в тот миг, когда она выйдет, а не проспать
--- свой срок целиком и уйти с отказом, так и не попробовав второй раз.
---
--- А если пауза уже вышла и больше открыть ничто не мешает, не спать
--- вовсе. Пауза выходит и до того, как взявший ляжет спать: между
--- отметкой отказа и сном пул пишет журнал, сборщик мусора вклинивается
--- в любую строку, и эта работа бывает длиннее короткой паузы. Сон
--- до побудки стал бы тогда сном до конца срока: будить некому. Пауза
--- в ноль этого не касается — она значит «пробовать на следующей
--- побудке», а не «пробовать без передышки», и после неё ждут побудки.
---@param now number
---@param deadline number
---@param ready boolean|nil Ждущий первый в очереди и место в пуле есть: мешать ему может только пауза
---@return number
function Module:sleep_span(now, deadline, ready)
    local blocked = self.blocked_until

    if blocked ~= nil and blocked > now then
        return math.min(deadline, blocked) - now
    end

    if ready and self.cooldown > 0 then
        return 0
    end

    return deadline - now
end

return Module
